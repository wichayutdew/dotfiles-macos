// Score Generated Content Quality — Dual Mode (Comparison or Absolute)
// Usage: node score.js [component] [lang_id]
//   If no args provided, scores all generated-*.csv files in OUTPUT_DIR
// Env vars:
//   OUTPUT_DIR         — output directory (required)
//   SCORE_MODE         — 'comparison' or 'absolute' (default: comparison)
//   SCORE_MODEL        — LLM model (default: gemini-3.1-pro-preview)
//   SCORE_CONCURRENCY  — parallel scoring workers (default: 5)
//   OPENAI_BASE_URL    — GenAI endpoint (default: https://genai-gateway.agoda.is/v1)

const OpenAI = require('openai');
const fs = require('fs');
const path = require('path');

const OUTPUT_DIR = process.env.OUTPUT_DIR;
if (!OUTPUT_DIR) { console.error('OUTPUT_DIR env var is required'); process.exit(1); }

const outputDir = path.resolve(OUTPUT_DIR);
const SCORE_MODE = (process.env.SCORE_MODE || 'comparison').toLowerCase();
if (!['comparison', 'absolute'].includes(SCORE_MODE)) {
  console.error(`ERROR: SCORE_MODE must be 'comparison' or 'absolute', got: ${SCORE_MODE}`);
  process.exit(1);
}

const SCORE_MODEL = process.env.SCORE_MODEL || 'gemini-3.1-pro-preview';
const SCORE_CONCURRENCY = Math.max(1, parseInt(process.env.SCORE_CONCURRENCY, 10) || 5);

const client = new OpenAI({
  baseURL: process.env.OPENAI_BASE_URL || 'https://genai-gateway.agoda.is/v1',
});

// Scoring prompts for each mode
const SCORING_PROMPTS = {
  comparison: (langName) => `You are an expert content quality evaluator for a travel booking platform (Agoda).
You will be given the ORIGINAL activity details (raw input from the content database) and GENERATED enhanced content (output from the GPT enhancement pipeline) in ${langName} language.
The enhanced content was generated by a GPT model to improve SEO and user experience.

Score each dimension 0-100 where 0=terrible, 50=no improvement, 100=perfect enhancement.

Dimensions:
- fluency: How natural and smooth the ${langName} text reads
- grammar: Correctness of ${langName} grammar, spelling, punctuation
- structure: User-friendly formatting, clear sections, readability
- relevance: Content stays true to the activity, no hallucination or irrelevant info
- completeness: Key activity details from the original input are preserved in the output
- tone: Appropriate travel/marketing tone, engaging but not overselling

Return ONLY a JSON object with these exact keys (no markdown, no explanation):
{"fluency":N,"grammar":N,"structure":N,"relevance":N,"completeness":N,"tone":N}`,

  absolute: (langName) => `You are an expert content quality evaluator for a travel booking platform (Agoda).
You will evaluate the quality of enhanced content for an activity listing in ${langName} language.
The content was generated by a GPT model for SEO and user experience improvement.

Score each dimension 0-100 where 0=terrible, 50=mediocre, 100=excellent.

Dimensions:
- fluency: How natural and smooth the ${langName} text reads
- grammar: Correctness of ${langName} grammar, spelling, punctuation
- structure: User-friendly formatting, clear sections, readability
- relevance: Content stays true to the activity, no hallucination or irrelevant info
- completeness: All key activity details are present
- tone: Appropriate travel/marketing tone, engaging but not overselling

Return ONLY a JSON object with these exact keys (no markdown, no explanation):
{"fluency":N,"grammar":N,"structure":N,"relevance":N,"completeness":N,"tone":N}`
};

// CSV utils
function parseCSVRow(row) {
  const fields = []; let current = ''; let inQuotes = false;
  for (let i = 0; i < row.length; i++) {
    const ch = row[i];
    if (inQuotes) {
      if (ch === '"' && row[i + 1] === '"') { current += '"'; i++; }
      else if (ch === '"') { inQuotes = false; }
      else { current += ch; }
    } else {
      if (ch === '"') { inQuotes = true; }
      else if (ch === ',') { fields.push(current); current = ''; }
      else { current += ch; }
    }
  }
  fields.push(current);
  return fields;
}

function csvEscape(str) {
  if (!str) return '';
  str = String(str).replace(/\r?\n/g, ' ').replace(/\s+/g, ' ').trim();
  if (str.includes(',') || str.includes('"')) {
    return '"' + str.replace(/"/g, '""') + '"';
  }
  return str;
}

// Score one activity
async function scoreActivity(activityId, component, langName, detailsFiltered, enhancedContent) {
  if (!enhancedContent || enhancedContent.trim() === '') {
    return { fluency: 0, grammar: 0, structure: 0, relevance: 0, completeness: 0, tone: 0, error: 'no_content' };
  }

  const systemPrompt = SCORING_PROMPTS[SCORE_MODE](langName);

  const userMessage = SCORE_MODE === 'comparison'
    ? `Activity ID: ${activityId} | Component: ${component} | Language: ${langName}

=== ORIGINAL DETAILS (input to enhancement pipeline) ===
${detailsFiltered.substring(0, 3000)}

=== GENERATED ENHANCED CONTENT (pipeline output) ===
${enhancedContent.substring(0, 3000)}`
    : `Activity ID: ${activityId} | Component: ${component} | Language: ${langName}

=== ENHANCED CONTENT ===
${enhancedContent.substring(0, 3000)}`;

  for (let attempt = 0; ; attempt++) {
    try {
      const response = await client.chat.completions.create({
        model: SCORE_MODEL,
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: userMessage },
        ],
        temperature: 0.1,
        max_tokens: 2000,
      });

      const text = response.choices[0].message.content.trim();
      const jsonMatch = text.match(/\{[\s\S]*\}/);
      if (!jsonMatch) throw new Error('No JSON in response');
      const scores = JSON.parse(jsonMatch[0]);
      for (const key of ['fluency', 'grammar', 'structure', 'relevance', 'completeness', 'tone']) {
        if (typeof scores[key] !== 'number' || scores[key] < 0 || scores[key] > 100) {
          scores[key] = Math.max(0, Math.min(100, Number(scores[key]) || 0));
        }
      }
      return { ...scores, error: '' };
    } catch (err) {
      const status = err.status || err.statusCode;
      const retryable = status === 429 || (status >= 500 && status < 600);
      if (retryable && attempt < 2) {
        const delay = 1000 * Math.pow(2, attempt);
        console.warn(`  [${component}-${langName}] Retry ${attempt + 1} for ${activityId}, waiting ${delay}ms`);
        await new Promise(r => setTimeout(r, delay));
        continue;
      }
      console.error(`  [${component}-${langName}] Score error ${activityId}: ${err.message.substring(0, 60)}`);
      return { fluency: 0, grammar: 0, structure: 0, relevance: 0, completeness: 0, tone: 0, error: err.message.substring(0, 80) };
    }
  }
}

// Get already-scored IDs
function getScoredIds(scoredCsvPath) {
  if (!fs.existsSync(scoredCsvPath)) return new Set();
  const lines = fs.readFileSync(scoredCsvPath, 'utf-8').split('\n').filter(l => l.trim());
  if (lines.length <= 1) return new Set();
  const ids = new Set();
  for (const line of lines.slice(1)) {
    const match = line.match(/^(\d+)/);
    if (match) ids.add(match[1]);
  }
  return ids;
}

// Append to CSV
let writeQueue = Promise.resolve();
function appendCSV(csvPath, row) {
  writeQueue = writeQueue.then(() => fs.appendFileSync(csvPath, row + '\n'));
  return writeQueue;
}

// Process one generated CSV
async function processGeneratedCsv(generatedCsvPath) {
  const basename = path.basename(generatedCsvPath, '.csv'); // e.g., "generated-title-1"
  const match = basename.match(/^generated-(.+)-(\d+)$/);
  if (!match) {
    console.warn(`Skipping unrecognized file: ${basename}`);
    return;
  }
  const [, component, langId] = match;

  const scoredCsvPath = path.join(outputDir, `scored-${component}-${langId}.csv`);
  const header = 'activity_id,component,language_id,fluency,grammar,structure,relevance,completeness,tone,score_mode,score_error';

  console.log(`\n[${component}-${langId}] Scoring mode: ${SCORE_MODE}`);
  console.log(`[${component}-${langId}] Input: ${generatedCsvPath}`);

  const lines = fs.readFileSync(generatedCsvPath, 'utf-8').split('\n').filter(l => l.trim());
  if (lines.length <= 1) {
    console.log(`[${component}-${langId}] No data rows, skipping.`);
    return;
  }

  const scoredIds = getScoredIds(scoredCsvPath);
  const dataRows = lines.slice(1).map(parseCSVRow).filter(fields => !scoredIds.has(fields[0]));

  console.log(`[${component}-${langId}] Total: ${lines.length - 1}, Already scored: ${scoredIds.size}, Remaining: ${dataRows.length}`);
  if (dataRows.length === 0) {
    console.log(`[${component}-${langId}] All done!`);
    return;
  }

  if (!fs.existsSync(scoredCsvPath)) {
    fs.writeFileSync(scoredCsvPath, header + '\n');
  }

  let scored = scoredIds.size;
  const dims = ['fluency', 'grammar', 'structure', 'relevance', 'completeness', 'tone'];
  const sums = dims.map(() => 0);
  let validCount = 0;

  async function processRow(fields) {
    const [activityId, comp, langIdStr, langName, detailsFiltered, enhancedContent, , genError] = fields;

    if (genError) {
      const row = [activityId, comp, langIdStr, 0, 0, 0, 0, 0, 0, SCORE_MODE, csvEscape('generation_error')].join(',');
      await appendCSV(scoredCsvPath, row);
      scored++;
      return;
    }

    const scores = await scoreActivity(activityId, comp, langName, detailsFiltered, enhancedContent);
    const row = [
      activityId, comp, langIdStr,
      scores.fluency, scores.grammar, scores.structure,
      scores.relevance, scores.completeness, scores.tone,
      SCORE_MODE, csvEscape(scores.error)
    ].join(',');
    await appendCSV(scoredCsvPath, row);

    const hasScores = dims.some(d => scores[d] > 0);
    if (hasScores) {
      validCount++;
      dims.forEach((d, i) => { sums[i] += scores[d]; });
    }

    scored++;
    if (scored % 5 === 0) console.log(`  [${component}-${langId}] ${scored}/${lines.length - 1} scored...`);
  }

  // Worker pool
  const queue = [...dataRows];
  const workers = Array.from({ length: SCORE_CONCURRENCY }, async () => {
    while (queue.length > 0) {
      const fields = queue.shift();
      if (fields) await processRow(fields);
    }
  });
  await Promise.all(workers);

  console.log(`\n[${component}-${langId}] === SCORING COMPLETE ===`);
  console.log(`[${component}-${langId}] Scored: ${validCount}/${lines.length - 1}`);
  console.log(`[${component}-${langId}] Averages:`);
  dims.forEach((d, i) => {
    const avg = validCount > 0 ? (sums[i] / validCount).toFixed(1) : 0;
    console.log(`  ${d.padEnd(15)} ${avg}`);
  });
  console.log(`[${component}-${langId}] Output: ${scoredCsvPath}`);
}

// Main
(async () => {
  const args = process.argv.slice(2);
  let filesToScore = [];

  if (args.length === 2) {
    // Score specific component + lang_id
    const [component, langId] = args;
    const generatedCsvPath = path.join(outputDir, `generated-${component}-${langId}.csv`);
    if (!fs.existsSync(generatedCsvPath)) {
      console.error(`ERROR: ${generatedCsvPath} not found`);
      process.exit(1);
    }
    filesToScore = [generatedCsvPath];
  } else if (args.length === 0) {
    // Score all generated-*.csv files
    const files = fs.readdirSync(outputDir);
    filesToScore = files
      .filter(f => f.startsWith('generated-') && f.endsWith('.csv'))
      .map(f => path.join(outputDir, f));
    if (filesToScore.length === 0) {
      console.error('ERROR: No generated-*.csv files found in OUTPUT_DIR');
      process.exit(1);
    }
  } else {
    console.error('Usage: node score.js [component] [lang_id]');
    console.error('  If no args, scores all generated-*.csv files in OUTPUT_DIR');
    process.exit(1);
  }

  console.log(`Scoring ${filesToScore.length} file(s) with mode: ${SCORE_MODE}, model: ${SCORE_MODEL}, concurrency: ${SCORE_CONCURRENCY}`);

  for (const file of filesToScore) {
    await processGeneratedCsv(file);
  }

  console.log('\n=== ALL FILES SCORED ===');
})();
