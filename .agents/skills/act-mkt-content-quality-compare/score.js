// Content Quality Scoring — Multi-language, section-aware version
// Usage: node score.js <locale>
// Env vars:
//   OUTPUT_DIR        — output directory (required, e.g., content-quality/ACTB-2314-xxx)
//   RUN_TAG           — optional tag for input/output filenames (e.g., "indonesia")
//   OPENAI_BASE_URL   — LLM endpoint (default: https://genai-gateway.agoda.is/v1)
//   SCORE_MODEL       — LLM model name (default: gemini-3.1-pro)
//   SCORE_CONCURRENCY — parallel scoring workers (default: 5)

